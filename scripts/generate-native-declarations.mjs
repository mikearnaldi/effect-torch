import { generateTypeDef } from "@napi-rs/cli"
import fs from "node:fs"
import path from "node:path"
import { spawnSync } from "node:child_process"
import { nativePackages, rootDirectory } from "./native-packages.mjs"

const args = process.argv.slice(2)
const check = args.includes("--check")
const packageIndex = args.indexOf("--package")
const packageName = packageIndex === -1 ? undefined : args[packageIndex + 1]
const knownArgs = new Set(["--check", "--package", packageName])
const unknownArg = args.find((arg) => !knownArgs.has(arg))

if (unknownArg !== undefined) {
  throw new Error(`unknown argument: ${unknownArg}`)
}
if (packageIndex !== -1 && packageName === undefined) {
  throw new Error("--package requires an npm or Cargo package name")
}

const selected = packageName === undefined
  ? nativePackages
  : nativePackages.filter((candidate) =>
    candidate.npmName === packageName || candidate.cargoName === packageName
  )

if (selected.length === 0) {
  throw new Error(`unknown native package: ${packageName}`)
}

const workDirectory = path.join(rootDirectory, "target/napi-type-def")
const cargoTarget = path.join(workDirectory, "cargo")
const stale = []

const allowExplicitUndefined = (declaration) =>
  declaration.replace(
    /^(\s+(?:readonly )?[A-Za-z_$][\w$]*\?: )(.+)$/gmu,
    (line, prefix, type) => /(?:^|\|)\s*undefined(?:\s*\||$)/u.test(type) ? line : `${prefix}${type} | undefined`
  )

const runCargo = (cargoArgs, environment = {}) => {
  const result = spawnSync("cargo", cargoArgs, {
    cwd: rootDirectory,
    env: { ...process.env, ...environment },
    stdio: "inherit"
  })
  if (result.error !== undefined) throw result.error
  if (result.status !== 0) {
    throw new Error(`cargo ${cargoArgs.join(" ")} failed with exit code ${result.status}`)
  }
}

for (const nativePackage of selected) {
  const typeDefDir = path.join(workDirectory, "metadata", nativePackage.cargoName)
  fs.rmSync(typeDefDir, { recursive: true, force: true })
  fs.mkdirSync(typeDefDir, { recursive: true })

  // Force the addon crate's proc macros to rerun while retaining compiled dependencies.
  runCargo([
    "clean",
    "--target-dir",
    cargoTarget,
    "--package",
    nativePackage.cargoName
  ])

  const cargoArgs = [
    "check",
    "--locked",
    "--target-dir",
    cargoTarget,
    "--package",
    nativePackage.cargoName
  ]
  if (nativePackage.cargoFeatures !== undefined) {
    cargoArgs.push(
      "--no-default-features",
      "--features",
      nativePackage.cargoFeatures.join(",")
    )
  }
  runCargo(cargoArgs, { NAPI_TYPE_DEF_TMP_FOLDER: typeDefDir })

  const { dts } = await generateTypeDef({
    typeDefDir,
    cwd: rootDirectory,
    noDtsHeader: true
  })
  const declaration = [
    "// Generated from the Rust N-API exports by `pnpm generate:native-types`.",
    "// Do not edit this file directly.",
    "",
    allowExplicitUndefined(dts.trimEnd()),
    "",
    'export type NativeAddon = typeof import("./native-addon.js")',
    ""
  ].join("\n")
  const output = path.join(nativePackage.directory, "src/internal/native-addon.d.ts")
  const current = fs.existsSync(output) ? fs.readFileSync(output, "utf8") : undefined

  if (current === declaration) {
    process.stdout.write(`Native declarations are current for ${nativePackage.npmName}\n`)
  } else if (check) {
    stale.push(path.relative(rootDirectory, output))
  } else {
    fs.writeFileSync(output, declaration)
    process.stdout.write(`Generated ${path.relative(rootDirectory, output)}\n`)
  }
}

if (stale.length > 0) {
  throw new Error(`native declarations are stale:\n${stale.map((file) => `  ${file}`).join("\n")}`)
}
